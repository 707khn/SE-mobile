def refusal(employee):
    """Ответ гостю на запрос, который что-то меняет; None — пропустить.

    Подписка телефона на пуши (/api/fcm-token) тоже закрыта: пуш «всем» —
    это объявления предприятия, гостю их видеть незачем.
    """
    if not is_demo(employee):
        return None
    if request.method in ('GET', 'HEAD', 'OPTIONS'):
        return None
    if request.endpoint in READ_BY_POST:
        return None
    return jsonify({'message': 'Failure', 'error': 'demo_read_only'}), 403


def directory():
    """Справочник гостевого мира — в том же виде, что /api/directory."""
    rows = []
    for _id, name, title, department, extension, mail in STAFF:
        rows.append((department.replace(' (демо)', ''), name, title,
                     extension, mail))
    rows.extend(_POSTS)
    order = []
    for row in rows:
        if row[0] not in order:
            order.append(row[0])
    rows.sort(key=lambda r: order.index(r[0]))
    return [{
        'department': department,
        'name': name,
        'position': position,
        'extension': extension,
        'email': f'{mail}@{_MAIL_DOMAIN}' if mail else '',
        'mobile': '',
    } for department, name, position, extension, mail in rows]
