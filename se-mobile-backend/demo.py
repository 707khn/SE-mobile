def is_demo_id(employee_id):
    return bool(employee_id) and str(employee_id).startswith(PREFIX)


def is_demo(employee):
    return employee is not None and is_demo_id(employee.employee_id)


def same_world(viewer, employee_id):
    """Из одного ли мира смотрящий и человек с этим номером.

    Пустой номер (окно медпункта без записи, техника на складе, объявление
    без автора) — мир настоящий.
    """
    return is_demo(viewer) == is_demo_id(employee_id)


def world(column, viewer):
    """Условие для запроса: только строки мира смотрящего.

    Без смотрящего (запрос без пропуска) — настоящий мир. Пустое значение
    столбца — тоже настоящий: гостевые строки всегда с номером.
    """
    guest = column.like(PREFIX + '%')
    if is_demo(viewer):
        return guest
    return or_(column.is_(None), not_(guest))


def real(column):
    """Только настоящий мир — для сводок по всему предприятию."""
    return world(column, None)


def world_ids():
    """Номера всех людей гостевого мира."""
    from models import Employee
    return {e.employee_id for e in
            Employee.query.filter(Employee.employee_id.like(PREFIX + '%'))}


# POST-ом, но только читают — или касаются лишь своего входа. Всё остальное,
# что не GET, гостю отвечает 403. Имена — как у функций маршрутов
