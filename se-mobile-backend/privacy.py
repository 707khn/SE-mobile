"""Политика конфиденциальности приложения — страница /privacy.

Google Play требует ссылку на неё в карточке приложения и в анкете о данных.
Она лежит здесь, на нашем же сервере, а не на стороннем сайте: адрес должен
жить столько же, сколько приложение, а текст — меняться вместе с ним.

Описано то, что приложение делает на самом деле. Добавилась новая обработка
данных — это место надо поправить в том же изменении.

Текст составлен по устройству приложения, а не юристом. Перед публикацией
его должен прочитать тот, кто отвечает на предприятии за персональные
данные, — и при необходимости поправить здесь.
"""

import html
import os

# Куда писать с вопросами о данных. Задаётся на сервере, в /etc/se-mobile.env:
# адрес может смениться, а пересобирать ради этого сервер незачем.
_DEFAULT_CONTACT = ('отдел информационных технологий и связи (ОИТиС) '
                    'АО «Семей инжиниринг»')

_UPDATED = '5 октября 2026 года'

_TEMPLATE = '''<!doctype html>
<html lang="ru">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>SE Mobile — политика конфиденциальности</title>
<style>
  body {{ font: 16px/1.55 -apple-system, "Segoe UI", Roboto, sans-serif;
         max-width: 760px; margin: 0 auto; padding: 24px 16px 48px;
         color: #1d1d1f; background: #fff; }}
  h1 {{ font-size: 1.6em; margin-bottom: .2em; }}
  h2 {{ font-size: 1.15em; margin-top: 1.8em; }}
  .muted {{ color: #5f6368; }}
  @media (prefers-color-scheme: dark) {{
    body {{ color: #e8eaed; background: #121212; }}
    .muted {{ color: #9aa0a6; }}
  }}
</style>
</head>
<body>
<h1>Политика конфиденциальности приложения SE Mobile</h1>
<p class="muted">Редакция от {updated}</p>

<p>SE Mobile — приложение для работников АО «Семей инжиниринг» (далее —
предприятие). В нём работник видит свой расчётный листок, отметки прохода
через проходную, остаток отпуска, меню столовой, новости и справочник
предприятия. Приложение публикует предприятие; оно же отвечает за данные,
которые в нём показываются.</p>

<p>Данные обрабатываются в соответствии с Законом Республики Казахстан
«О персональных данных и их защите».</p>

<h2>Кто может пользоваться приложением</h2>
<p>Только работники предприятия. Учётные записи заводит предприятие;
зарегистрироваться в приложении самостоятельно нельзя. Вход — по табельному
номеру и паролю.</p>

<h2>Какие данные показывает приложение</h2>
<p>Эти данные ведёт предприятие в своих учётных системах, а приложение
только показывает их самому работнику:</p>
<ul>
  <li>фамилия, имя, отчество, табельный номер, должность, подразделение;</li>
  <li>расчётные листки: начисления, удержания, суммы к выплате;</li>
  <li>отметки прохода через проходную: дата, время, направление, точка
      прохода;</li>
  <li>остатки и история отпусков;</li>
  <li>служебный справочник: ФИО, должности, рабочие телефоны и адреса
      электронной почты работников.</li>
</ul>
<p>Руководители и уполномоченные работники видят в приложении отметки
прохода своих подчинённых — в том объёме, который им разрешает
предприятие.</p>

<h2>Что приложение передаёт с телефона</h2>
<ul>
  <li><b>Табельный номер и пароль</b> — при входе, чтобы проверить, что это
      вы. Пароль на сервере хранится только в виде хеша, по которому его
      нельзя восстановить.</li>
  <li><b>Номер версии приложения</b> — с каждым запросом, чтобы знать, у
      кого установлена устаревшая версия.</li>
  <li><b>Токен для уведомлений</b> — если уведомления включены. Это
      случайный идентификатор, который выдаёт служба Google Firebase Cloud
      Messaging, чтобы доставить уведомление на ваш телефон.</li>
</ul>
<p><b>Заявки в ОИТиС</b>: кабинет, описание, телефон для связи и
фотографии, которые вы сами прикрепили к заявке. Их видят только вы и
сотрудники ОИТиС; фотографии удаляются через полгода после закрытия заявки.</p>
<p>Кроме этого, приложение не собирает геолокацию, контакты, фотографии,
файлы с телефона и сведения о других установленных приложениях. В нём нет рекламы
и сторонней аналитики.</p>

<h2>Что хранится на самом телефоне</h2>
<p>Пропуск для входа хранится в защищённом хранилище телефона. Последние
загруженные данные (меню, расчётный листок, отпуск, проходы) сохраняются, чтобы их
можно было открыть без связи; при выходе из учётной записи они стираются. Выгрузки в
Excel и CSV, которые вы создаёте сами, сохраняются в папку приложения.</p>

<h2>Где хранятся данные и кому передаются</h2>
<p>Данные хранятся на сервере предприятия в Республике Казахстан и
передаются между телефоном и сервером только по защищённому соединению
(HTTPS). Третьим лицам данные не продаются и не передаются, кроме:</p>
<ul>
  <li>Google Firebase Cloud Messaging — только токен устройства и текст
      уведомления, для его доставки;</li>
  <li>случаев, предусмотренных законодательством Республики Казахстан.</li>
</ul>

<h2>Сколько хранятся данные</h2>
<p>Столько, сколько их требует хранить трудовое и налоговое
законодательство, и не дольше, чем это нужно предприятию для исполнения
трудовых отношений. Учётную запись в приложении отключает администратор
предприятия, когда в ней больше нет необходимости.</p>

<h2>Ваши права</h2>
<p>Вы можете узнать, какие данные о вас обрабатываются, потребовать
исправить неточные или удалить свою учётную запись в приложении. Для этого
обратитесь: {contact}.</p>

<h2>Изменения</h2>
<p>Если порядок обработки данных изменится, эта страница будет обновлена;
дата редакции указана вверху.</p>
</body>
</html>
'''


def privacy_page():
    """HTML страницы политики — с контактом, заданным на сервере."""
    contact = os.environ.get('PRIVACY_CONTACT', '').strip() or _DEFAULT_CONTACT
    return _TEMPLATE.format(updated=_UPDATED, contact=html.escape(contact))
