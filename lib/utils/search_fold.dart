/// Поиск, которому всё равно, на какой раскладке набирают.
///
/// В справочнике предприятия у двенадцати человек из 123 в имени есть буквы,
/// которых на русской раскладке нет вовсе: «Асқаров Қайрат Мейрамұлы» —
/// Генеральный директор, «Тілеуғали Еркінғали Тілеуғалиұлы», «Омаргалиева
/// Меруетгүль Кабылкаковна». Телефон по умолчанию открывает русскую
/// клавиатуру, и найти их можно было, только переключив раскладку и вспомнив,
/// где там `қ`.
///
/// Поэтому обе стороны — и то, что набрали, и то, в чём ищем, — приводятся к
/// общему виду: казахские буквы заменяются ближайшими русскими. «Аскаров»
/// находит «Асқаров», «Тилеугали» — «Тілеуғали», и наоборот тоже.
///
/// Замена нужна только для поиска. Показываем всегда настоящее написание:
/// человека зовут так, как его зовут.
const Map<String, String> _fold = <String, String>{
  'ә': 'а', 'ғ': 'г', 'қ': 'к', 'ң': 'н', 'ө': 'о',
  'ұ': 'у', 'ү': 'у', 'һ': 'х', 'і': 'и',
  // Не казахская, но из того же теста: «ё» набирают через «е» почти всегда.
  'ё': 'е',
};

String foldForSearch(String raw) {
  final lower = raw.toLowerCase();
  final buffer = StringBuffer();
  for (final rune in lower.runes) {
    final char = String.fromCharCode(rune);
    buffer.write(_fold[char] ?? char);
  }
  return buffer.toString();
}

/// Есть ли [query] в [text], если не придираться к раскладке.
bool matchesQuery(String text, String query) =>
    foldForSearch(text).contains(foldForSearch(query));
