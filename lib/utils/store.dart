/// Через какой канал пришло приложение.
///
/// Собирается одна и та же программа, но для двух каналов:
/// `flutter build appbundle --dart-define=STORE=play` — для Google Play,
/// обычная сборка — для раздачи файлом с нашего сервера. То же значение
/// читает android/app/build.gradle и даёт сборке для Play своё имя пакета.
const String kStore = String.fromEnvironment('STORE');

/// Сборка из Google Play.
///
/// Такое приложение обновляет только Play: правила магазина запрещают
/// приложению скачивать и ставить новые версии в обход него, и за это
/// снимают с публикации. Поэтому в ней молчит своя проверка обновлений.
const bool kFromPlay = kStore == 'play';
