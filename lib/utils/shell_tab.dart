import 'package:flutter/foundation.dart';

/// Какая вкладка открыта. Одна на всё приложение.
///
/// Нужна затем, что до неё переход на вкладку из бокового меню — когда меню
/// открыли не с самой вкладки, а с «Справочника» или «Новостей» — делался так:
///
/// ```dart
/// Get.offAll(() => HomeShell(..., initialIndex: index));
/// ```
///
/// То есть оболочка **создавалась заново**. Вместе с ней заново создавались все
/// пять вкладок, уходило пять запросов к серверу, а открытый расчётный лист,
/// выбранный период и прокрутка пропадали. Человек нажимал «Проходы» и заодно
/// терял всё, что успел настроить.
///
/// Теперь оболочка одна на весь сеанс: меню меняет здесь число, оболочка его
/// слышит, а стопка открытых поверх экранов просто сворачивается.
class ShellTab {
  ShellTab._();

  static final ValueNotifier<int> selected = ValueNotifier<int>(0);

  static void open(int index) => selected.value = index;
}
