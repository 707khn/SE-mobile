/// Первые буквы фамилии и имени — для кружка вместо фотографии.
///
/// Слова делятся по любому числу пробелов. В табеле проходов делили по
/// одному, и на ФИО с двойным пробелом — в выгрузке из 1С такое бывает —
/// между пробелами выходило пустое «слово», а на его первой букве строка
/// падала.
String initialsOf(String name) {
  final words =
      name.trim().split(RegExp(r'\s+')).where((w) => w.isNotEmpty);
  if (words.isEmpty) return '?';
  return words.take(2).map((w) => w[0]).join().toUpperCase();
}
