/// Через сколько минут снова можно войти — из секунд, присланных сервером.
///
/// Округляем вверх: «через 0 мин.» при оставшихся сорока секундах звучит как
/// «уже можно», человек пробует — и снова натыкается на замок. `null`, если
/// сервер срока не назвал: тогда пишем «попробуйте немного позже».
int? lockMinutes(int? seconds) {
  if (seconds == null || seconds <= 0) return null;
  return (seconds + 59) ~/ 60;
}
