import 'dart:math' as math;

/// Эталонный телефон, по которому названы все размеры: 392×800.
const double kReferenceWidth = 392;
const double kReferenceHeight = 800;

/// Насколько увеличить размеры на этом экране относительно эталонного.
///
/// Пропорция — но с ограничением, и оно здесь главное. Без него размеры
/// множились на отношение экранов как есть, и получалось так:
///
/// | экран | «кегль 14» |
/// |---|---|
/// | 320×640, дешёвый телефон | **11,5** |
/// | 392×800, обычный | 14,3 |
/// | 800×1280, планшет | **22,9** |
///
/// То есть у кого телефон хуже, у того и буквы мельче. На заводе это ровно те
/// люди, которые читают расчётный лист на солнце и в перчатках. Меньший экран
/// требует относительно более крупного текста, а не более мелкого.
///
/// Пределы узкие намеренно. Цель — не «подогнать под каждый экран», а не дать
/// размерам уехать: на обычном телефоне всё остаётся ровно как было.
double uiScale(double screenSize, double reference) {
  if (screenSize <= 0 || reference <= 0) return 1;
  return math.min(math.max(screenSize / reference, 0.92), 1.15);
}
